#!/usr/bin/env node
/**
 * `npm run catalogue` — generate, then gate (SPEC §19.4 rule 3, §11.2).
 *
 * From src/server/capabilities/catalogue.js it generates:
 *   src/server/capabilities/catalogue.snapshot.json   what the parity gate validates capability names against
 *   docs/AGENT-CAPABILITIES.md                        the human catalogue (§11.2)
 *
 * Without --write it fails when either committed copy differs from what the catalogue generates now, so a
 * declaration cannot change without its generated surfaces changing in the same commit.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOGUE } from '../src/server/capabilities/catalogue.js';
import { toWire } from '../src/server/capabilities/define.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SNAPSHOT = join(ROOT, 'src', 'server', 'capabilities', 'catalogue.snapshot.json');
const DOC = join(ROOT, 'docs', 'AGENT-CAPABILITIES.md');

export function snapshot() {
  return JSON.stringify({ $generated: 'npm run catalogue -- --write', capabilities: CATALOGUE.map((c) => ({ name: c.name, wire: toWire(c.name), version: c.version, class: c.class, scope: c.scope, surfaces: c.surfaces, aliases: c.aliases })) }, null, 1) + '\n';
}

export function doc() {
  const L = ['# XENO platform — agent capabilities', '', '> GENERATED by `npm run catalogue -- --write` from `src/server/capabilities/catalogue.js`. Do not edit by hand; `npm run catalogue` fails when this is stale.', '',
    `What an agent can do on the XENO platform: **${CATALOGUE.length} capabilities**. What it cannot do yet is \`docs/AGENT-PARITY-DEBT.md\`. Served on \`/api/mcp\` under the wire name; the alias keeps working.`, ''];
  const byDiv = {};
  for (const c of CATALOGUE) (byDiv[c.division] ||= []).push(c);
  for (const div of Object.keys(byDiv).sort()) {
    L.push(`## ${div}`, '', '| capability | wire | class | cost | idempotency | preview | served on | alias |', '|---|---|---|---|---|---|---|---|');
    for (const c of byDiv[div]) L.push(`| \`${c.name}\`${c.agentsOnly ? ' (agents)' : ''} | \`${toWire(c.name)}\` | ${c.class} | ${c.cost.model} | ${c.idempotency.strategy === 'key' ? `key \`${c.idempotency.key}\`` : c.idempotency.strategy} | ${c.preview.supported ? 'yes' : 'no'} | ${c.surfaces.join(', ')} | ${c.aliases.map((a) => `\`${a}\``).join(' ')} |`);
    L.push('');
    for (const c of byDiv[div]) {
      const args = Object.entries((c.input && c.input.properties) || {}).map(([k, v]) => `\`${k}\`${(c.input.required || []).includes(k) ? '*' : ''}${v.type ? ` ${v.type}` : ''}`).join(', ') || 'none';
      const reply = Object.entries(c.reply.properties || {}).map(([k, v]) => `\`${k}\` — ${v.description || v.type || ''}`).join('; ');
      L.push(`- **\`${c.name}\`** — ${c.description.replace(/\s+/g, ' ')}`, `  - arguments: ${args}`, `  - reply: ${reply || '—'}`);
    }
    L.push('');
  }
  return L.join('\n');
}

const norm = (s) => s.replace(/\r\n/g, '\n');
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = [[SNAPSHOT, snapshot()], [DOC, doc()]];
  if (process.argv.includes('--write')) { for (const [p, s] of out) writeFileSync(p, s); console.log(`catalogue: wrote ${CATALOGUE.length} capabilities`); }
  else {
    const stale = out.filter(([p, s]) => !existsSync(p) || norm(readFileSync(p, 'utf8')) !== s).map(([p]) => p);
    if (stale.length) { console.error(`catalogue: stale generated files — run npm run catalogue -- --write:\n  ${stale.join('\n  ')}`); process.exit(1); }
    console.log(`catalogue OK — ${CATALOGUE.length} capabilities, generated files current`);
  }
}
