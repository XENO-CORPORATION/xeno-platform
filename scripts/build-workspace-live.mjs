#!/usr/bin/env node
// Builds the XENO Multiplayer client the workspace uses (prototypes/xeno-workspace/live-client.js): the workspace is
// plain scripts, so it carries one IIFE with @xenosystem/primitives/live and the one Yjs it needs. Committed like
// docs-editor.js. Run after a version bump below. Yjs and the client are built together because Yjs breaks when two
// copies meet. They're installed in a temporary folder, not package.json: nothing on the server may load them.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const PRIMITIVES = '0.4.0', YJS = '13.6.27';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = mkdtempSync(join(tmpdir(), 'xeno-live-client-'));
try {
  execFileSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['install', '--no-save', '--ignore-scripts', '--no-audit', '--no-fund', `yjs@${YJS}`, `@xenosystem/primitives@${PRIMITIVES}`],
    { cwd: dir, stdio: 'ignore', shell: process.platform === 'win32' });
  const outfile = join(root, 'prototypes', 'xeno-workspace', 'live-client.js');
  await build({
    stdin: { contents: "export * as Y from 'yjs';\nexport { joinLive, liveCloseReason } from '@xenosystem/primitives/live';\n", resolveDir: dir, sourcefile: 'live-client-entry.js', loader: 'js' },
    outfile, bundle: true, format: 'iife', globalName: 'XenoLive', platform: 'browser', target: 'es2022', minify: true, legalComments: 'none',
    banner: { js: `/* Generated by scripts/build-workspace-live.mjs: @xenosystem/primitives@${PRIMITIVES}, yjs@${YJS} (MIT, Kevin Jahns). Do not edit. */` },
  });
  console.log(`live-client.js ${(readFileSync(outfile).length / 1024).toFixed(0)} KB`);
} finally { rmSync(dir, { recursive: true, force: true }); }
