#!/usr/bin/env node
/**
 * The two release gates that say, in the plan's own words, **"verified by
 * exceeding it, not by reading the config."**
 *
 *   §5 Functional — a new account cannot post more than n threads/hour, and an
 *                   agent's budget is separate and tighter.
 *   §5 Loop D     — an agent that exceeds `max_per_hour` is refused, and the
 *                   refusal is visible to its owner.
 *
 * A rate limit is the easiest thing in a codebase to get wrong invisibly: the
 * table reads correctly, the constants are sensible, the code that consults them
 * looks right, and it never fires because the query counts the wrong window or
 * the caller was never routed through it. Reading it proves nothing. So this
 * exceeds every limit and asserts the refusal — its code, its status, and for a
 * new account the WORDING, because "rate limit reached" on somebody's first hour
 * reads as a broken product and "new accounts are limited for the first day"
 * reads as a rule.
 *
 * ── WHY THE DIGEST HALF IS HERE AT ALL ──────────────────────────────────────
 *
 * 🔴 `max_per_hour` was enforced in the REST route only. The MCP `forum_digest`
 * tool called the service directly — so an AGENT, the exact caller the limit
 * exists to restrain, bypassed it entirely by choosing the other surface. The
 * limit now lives in `getDigest`, and this proves it fires on BOTH.
 *
 * ── SAFETY ──────────────────────────────────────────────────────────────────
 *
 *   • Dry-run by DEFAULT; `--confirm` required.
 *   • 🔴 NOTHING IS EVER COMMITTED — one transaction, always rolled back. It
 *     creates ~20 threads to exhaust a budget; none of them survive.
 */

import crypto from 'crypto';
import pg from 'pg';

const CONFIRM = process.argv.includes('--confirm');

let failures = 0;
const pass = (m) => console.log(`  ok    ${m}`);
const fail = (m) => { console.log(`  FAIL  ${m}`); failures += 1; };

const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL });

async function service(name) {
  const dir = process.env.FORUM_SERVICE_DIR;
  const candidates = dir
    ? [new URL(`${dir.replace(/\/$/, '')}/${name}`, 'file:///').href]
    : [`../src/server/services/${name}`, `../services/${name}`];
  for (const p of candidates) {
    try { return await import(p); } catch (err) {
      if (err.code !== 'ERR_MODULE_NOT_FOUND') throw err;
    }
  }
  throw new Error(`cannot locate ${name} in either layout`);
}

/** Clone a real user row; `ageHours` back-dates it past the new-account window. */
async function cloneUser(client, sourceId, label, ageHours = 0) {
  const { rows: cols } = await client.query(
    `SELECT column_name FROM information_schema.columns
      WHERE table_name = 'users' ORDER BY ordinal_position`,
  );
  const names = cols.map((c) => c.column_name);
  const uniq = crypto.randomBytes(4).toString('hex');

  const select = names.map((n) => {
    if (n === 'id') return 'gen_random_uuid() AS id';
    if (n === 'email') return `'thr-${uniq}@example.invalid' AS email`;
    if (['handle', 'username', 'display_name'].includes(n)) return `'${label}${uniq}' AS ${n}`;
    if (n === 'created_at') return `(NOW() - INTERVAL '${Number(ageHours)} hours') AS created_at`;
    if (n === 'role') return `'user' AS role`;
    return `"${n}"`;
  }).join(', ');

  const { rows } = await client.query(
    `INSERT INTO users (${names.map((n) => `"${n}"`).join(', ')})
     SELECT ${select} FROM users WHERE id = $1 RETURNING id`,
    [sourceId],
  );
  return rows[0].id;
}

/**
 * Create threads until one is refused, and report where it stopped.
 *
 * Returns { made, error }. Deliberately bounded well above any cap: a limit that
 * never fires must end this loop with a number, not a hang.
 */
async function postUntilRefused(write, client, actor, max = 25) {
  let made = 0;
  for (let i = 0; i < max; i += 1) {
    try {
      await write.createThread(client, actor, {
        space: 'help',
        title: `Throttle proof thread ${i} ${crypto.randomBytes(3).toString('hex')}`,
        body: 'Generated by the throttle proof. This transaction is rolled back.',
      });
      made += 1;
    } catch (err) {
      return { made, error: err };
    }
  }
  return { made, error: null };
}

const client = await pool.connect();
let began = false;

try {
  const { rows: admins } = await client.query(
    "SELECT id, email FROM users WHERE role = 'admin' ORDER BY created_at LIMIT 1",
  );
  if (!admins.length) throw new Error('no admin account');

  if (!CONFIRM) {
    console.log('DRY RUN — would open a transaction, exhaust the thread budget of an');
    console.log('established human, a new human and a new agent, exceed a digest');
    console.log('predicate on both REST and MCP, and ROLL BACK. Nothing is committed');
    console.log('even with --confirm. Re-run with --confirm to execute.');
    process.exit(0);
  }

  await client.query('BEGIN');
  began = true;

  const write = await service('forumWrite.js');
  const svc = await service('forumService.js');
  const mcp = await service('forumMcp.js');
  const ident = await service('agentIdentity.js');

  const actorOf = async (id) => {
    const p = await ident.resolvePrincipal(client, id);
    return { id: p.id, username: p.handle, display_name: p.displayName, role: p.role, kind: p.kind, owner: p.owner };
  };

  // ── 1. an ESTABLISHED human: 10 threads/hour ─────────────────────────────
  console.log('1. established human (created 48h ago) — cap is 10 threads/hour:');
  const humanId = await cloneUser(client, admins[0].id, 'thrhuman', 48);
  const human = await actorOf(humanId);
  const r1 = await postUntilRefused(write, client, human);

  if (!r1.error) fail(`made ${r1.made} threads and was NEVER refused — the limit does not fire`);
  else if (r1.made !== 10) fail(`refused after ${r1.made} threads, expected 10`);
  else pass('refused on the 11th thread');

  if (r1.error?.code !== 'rate_limited') fail(`refusal code is "${r1.error?.code}", expected rate_limited`);
  else pass('code = rate_limited');
  if (r1.error?.statusCode !== 429) fail(`refusal status is ${r1.error?.statusCode}, expected 429`);
  else pass('status = 429');

  // ── 2. a NEW human: 3 threads/hour, and it must SAY it is temporary ──────
  console.log('\n2. new human (created just now) — cap is 3 threads/hour:');
  const newHumanId = await cloneUser(client, admins[0].id, 'thrnew', 0);
  const newHuman = await actorOf(newHumanId);
  const r2 = await postUntilRefused(write, client, newHuman);

  if (!r2.error) fail(`a brand-new account made ${r2.made} threads unchallenged — this is the shape every spam run relies on`);
  else if (r2.made !== 3) fail(`refused after ${r2.made} threads, expected 3`);
  else pass('refused on the 4th thread');

  if (r2.made >= r1.made) fail('a new account is not tighter than an established one');
  else pass(`new-account budget is tighter (${r2.made} vs ${r1.made})`);

  // The wording is a product decision, not a nicety: a rule with an end date is
  // one people wait out; a bare "rate limit reached" is one they leave over.
  if (!/New accounts are limited/i.test(r2.error?.message || '')) {
    fail(`the refusal does not explain itself: "${r2.error?.message}"`);
  } else pass('the refusal says WHY, and that it is temporary');

  // ── 3. an AGENT: tighter still, and its budget is its OWN ────────────────
  console.log('\n3. agent owned by the established human — must be tighter, and separate:');
  const agent = await ident.createAgent(client, { id: human.id, kind: 'human', handle: human.username, role: 'user' }, {
    name: 'throttleproof',
    displayName: 'Throttle Proof Agent',
    agentRole: 'reporter',
    agentOrigin: 'proof',
  });
  // createAgent returns { agent: { handle, … }, apiKey } — an identity, not a
  // row id, because the id is deliberately not part of its public shape.
  const { rows: agentRows } = await client.query(
    'SELECT id FROM users WHERE LOWER(username) = LOWER($1)',
    [agent.agent.handle],
  );
  if (!agentRows.length) throw new Error(`created agent ${agent.agent.handle} has no user row`);
  const agentActor = await actorOf(agentRows[0].id);

  if (agentActor.kind !== 'agent') fail(`the created principal resolves as "${agentActor.kind}", not agent`);
  else pass('the agent resolves as kind=agent with an owner chain');

  const r3 = await postUntilRefused(write, client, agentActor);
  if (!r3.error) fail(`the agent made ${r3.made} threads unchallenged`);
  else pass(`agent refused after ${r3.made} thread(s)`);

  if (r3.made >= r2.made) fail(`an agent's budget (${r3.made}) is not tighter than a new human's (${r2.made}) — §4.3 says it must be`);
  else pass(`agent budget is tighter than a human's (${r3.made} vs ${r2.made})`);

  // 🔴 SEPARATE, not shared. If the counter were keyed on the owner, exhausting
  // the agent would silently spend its owner's budget — and a person would be
  // locked out of the forum by something their agent did.
  const ownerAfter = await postUntilRefused(write, client, human, 1);
  if (ownerAfter.error?.code !== 'rate_limited') {
    fail('the owner was expected to still be at its own cap independently');
  } else pass('the owner\'s budget is unchanged by its agent — the two are separate counters');

  // ── 4. the digest limit, on BOTH surfaces ────────────────────────────────
  console.log('\n4. digest max_per_hour — the rule an agent could previously dodge:');
  await svc.setPredicate(client, human.id, { max_per_hour: 1 });

  const first = await svc.getDigest(client, human.id, { channel: 'pull' });
  if (!first) fail('the first digest did not return');
  else pass('first digest returned');

  let refused = null;
  try {
    await svc.getDigest(client, human.id, { channel: 'pull' });
  } catch (err) { refused = err; }

  if (!refused) fail('a SECOND digest inside the window was served — max_per_hour is decoration');
  else if (refused.code !== 'digest_rate_limited') fail(`refusal code is "${refused.code}"`);
  else pass('REST/service path: second digest refused with digest_rate_limited');

  if (!(refused?.details?.retryAfterSeconds > 0)) {
    fail('the refusal carries no retryAfterSeconds — an agent can only respond by retrying blindly');
  } else pass(`refusal carries retryAfterSeconds=${refused.details.retryAfterSeconds}`);

  // 🔴 THE SURFACE THAT USED TO BYPASS IT.
  const mcpRes = await mcp.callTool(client, human, 'forum_digest', {});
  const mcpText = mcpRes?.content?.[0]?.text || JSON.stringify(mcpRes);
  if (!mcpRes?.isError) {
    fail('MCP served a digest inside the window — the limit is still enforced on one surface only');
  } else if (!/digest_rate_limited/.test(mcpText)) {
    fail(`MCP failed for a different reason: ${mcpText.slice(0, 90)}`);
  } else pass('MCP path: refused with digest_rate_limited — both surfaces now honour it');
} finally {
  if (began) {
    await client.query('ROLLBACK').catch(() => {});
    console.log('\nROLLED BACK — no user, agent, thread or subscription was committed.');
  }
  client.release();
  await pool.end();
}

console.log('');
if (failures) {
  console.log(`${failures} check(s) failed.`);
  process.exit(1);
}
console.log('Both throttle gates verified BY EXCEEDING THEM, on every surface.');
