#!/usr/bin/env node
// The v2 product-page chrome, for the React pages that sit under a design page:
// /product/<slug>/download, /releases and /releases/<version>.
//
// Those addresses are React routes, but a visitor reaches them from the v2
// design (the design's Download button lands on /download when no grant is
// attached). They must look like the page they came from, so their chrome is
// DERIVED from the same sources the designs use instead of being restyled by hand:
//   - the header markup comes from scripts/lib/marketing-header.mjs, the generator
//     the importer stamps into every design document;
//   - each product's accent is the colour of the first eyebrow in its design.
//
// Usage: node scripts/generate-v2-chrome.mjs           (write src/generated/v2Chrome.ts)
//        node scripts/generate-v2-chrome.mjs --check   (exit 1 if the file is stale)
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { marketingHeader } from './lib/marketing-header.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src', 'generated', 'v2Chrome.ts');
const PRODUCT_TOKEN = '__XENO_PRODUCT__';

const version = file => createHash('sha256').update(readFileSync(join(root, 'public', 'site', file))).digest('hex').slice(0, 16);
const header = marketingHeader({ product: PRODUCT_TOKEN });
if (!header.includes(PRODUCT_TOKEN)) throw new Error('marketing header no longer carries the product name');

// First eyebrow colour of each design: the mono, uppercase label above the hero headline.
const pagesDir = join(root, 'public', 'product-pages');
const accents = {};
for (const e of readdirSync(pagesDir, { withFileTypes: true }).filter(d => d.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
  const html = readFileSync(join(pagesDir, e.name, 'index.html'), 'utf8');
  const hero = html.slice(html.indexOf('data-screen-label="Hero"'));
  const m = hero.match(/text-transform:uppercase;\s*color:(#[0-9A-Fa-f]{6})/);
  if (m) accents[e.name] = m[1].toUpperCase();
}

const body = `// GENERATED by scripts/generate-v2-chrome.mjs — do not hand-edit.
// Regenerate after the marketing header, its assets or a design page changes;
// scripts/v2-chrome.test.mjs fails while this file is stale.

/** The shared marketing header. ${PRODUCT_TOKEN} is replaced with the escaped product word. */
export const V2_HEADER_HTML: string = ${JSON.stringify(header)};
export const V2_PRODUCT_TOKEN = ${JSON.stringify(PRODUCT_TOKEN)};
export const V2_HEADER_CSS = ${JSON.stringify(`/site/marketing-header.css?v=${version('marketing-header.css')}`)};
export const V2_HEADER_JS = ${JSON.stringify(`/site/marketing-header.js?v=${version('marketing-header.js')}`)};

/** Each product's accent: the first eyebrow colour in its v2 design. */
export const V2_ACCENTS: Readonly<Record<string, string>> = ${JSON.stringify(accents, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== body) { console.error('src/generated/v2Chrome.ts is stale: run node scripts/generate-v2-chrome.mjs'); process.exit(1); }
  console.log(`v2 chrome current: header + ${Object.keys(accents).length} accents`);
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body);
  console.log(`v2 chrome written: header + ${Object.keys(accents).length} accents`);
}
