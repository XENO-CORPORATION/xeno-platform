// The workspace's copy of the platform theme, GENERATED from the platform's own module.
//
// The platform theme is a brightness line of twenty-one stops (src/platform/platformThemePalette.ts).
// The workspace (prototypes/xeno-workspace) is plain scripts and cannot import TypeScript, so it reads
// a generated table: prototypes/xeno-workspace/theme-palette.js. This script RUNS the real module and
// writes what it returns, so the workspace holds no second copy of the palette or of its contrast rules.
//
//   node scripts/gen-workspace-theme.mjs           write the file
//   node scripts/gen-workspace-theme.mjs --check   exit 1 if the file is out of date (the drift gate)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'src/platform/platformThemePalette.ts');
const target = path.join(root, 'prototypes/xeno-workspace/theme-palette.js');

export async function build() {
  const ts = createRequire(import.meta.url)('typescript');
  const js = ts.transpileModule(fs.readFileSync(source, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
  const mod = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
  const step = mod.THEME_BRIGHTNESS_STEP;
  const stops = [];
  for (let position = 0; position <= 100; position += step) {
    const t = mod.getThemePreviewTokens(position);
    stops.push([t.canvas, t.surface, t.elevated, t.control, t.controlStrong, t.text, t.muted, t.border, t.hover, t.overlay, mod.getRelativeLuminance(t.canvas) > 0.45 ? 1 : 0]);
  }
  if (stops.length !== 21) throw new Error(`expected 21 stops, got ${stops.length}`);
  const named = Object.fromEntries(mod.VISUAL_CHAT_THEME_OPTIONS.map((o) => [o.id, o.position]));
  return `// GENERATED by scripts/gen-workspace-theme.mjs from src/platform/platformThemePalette.ts — do not edit by hand.
// One row per brightness stop (0, ${step}, … 100): canvas, surface, elevated, control, controlStrong, text, muted, border, hover, overlay, isLight.
window.XENO_THEME_PALETTE = { step: ${step}, named: ${JSON.stringify(named)}, stops: [
${stops.map((s) => '  ' + JSON.stringify(s)).join(',\n')}
] };
`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const out = await build();
  const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;
  if (process.argv.includes('--check')) {
    if (have !== out) { console.error('prototypes/xeno-workspace/theme-palette.js is out of date. Run: node scripts/gen-workspace-theme.mjs'); process.exit(1); }
    console.log('theme-palette.js matches the platform palette');
  } else {
    fs.writeFileSync(target + '.tmp', out, 'utf8'); fs.renameSync(target + '.tmp', target);
    console.log(have === out ? 'theme-palette.js already up to date' : 'wrote prototypes/xeno-workspace/theme-palette.js');
  }
}
