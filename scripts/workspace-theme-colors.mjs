// The workspace's stylesheets on the theme: every hard-coded grey becomes a colour derived from the theme.
//
// The workspace (prototypes/xeno-workspace) was written for one dark palette, with some 150 distinct greys typed
// in as hex. A theme that changes --canvas and --text cannot reach those, so in Light the page stayed dark in
// patches. A grey is a point between the page colour and the text colour, so each one is rewritten as exactly
// that:  --n31: color-mix(in srgb, var(--text) 8.8%, var(--canvas))   (n31 = lightness 31 of 255 in Dark).
// In Dark the result is the grey that was typed (to within one step); in Light the same rule gives the mirrored
// grey; at every stop between, it follows. White-with-alpha (hairlines, hovers) becomes text-with-alpha: --w60.
//
// Left alone on purpose: colours with a hue (status, product marks), pure black (shadows and scrims are black
// in every theme), anything inside url(...), and the :root block that defines the base tokens.
//
//   node scripts/workspace-theme-colors.mjs           rewrite the files and (re)write the scale block
//   node scripts/workspace-theme-colors.mjs --check   exit 1 if a stylesheet still has a hard-coded grey
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'prototypes', 'xeno-workspace');
const START = '/* theme scale — GENERATED by scripts/workspace-theme-colors.mjs; do not edit */', END = '/* end theme scale */';
const DARK_CANVAS = 10, DARK_TEXT = 250;   // #0a0a0a and #fafafa: the Dark stop every grey here was typed against

const hexRgb = (h) => { const s = h.length === 3 ? h.replace(/./g, '$&$&') : h; return [0, 2, 4].map((i) => parseInt(s.slice(i, i + 2), 16)); };
export function greyVar(hex) {
  const [r, g, b] = hexRgb(hex), spread = Math.max(r, g, b) - Math.min(r, g, b), L = Math.round((r + g + b) / 3);
  if (spread > 14) return null;      // a hue, not a grey
  if (L < 6) return null;            // true black: shadows, scrims
  return `--n${L}`;
}
export const greyValue = (L) => (L <= DARK_CANVAS ? 'var(--canvas)' : L >= DARK_TEXT ? 'var(--text)' : `color-mix(in srgb,var(--text) ${Math.round(((L - DARK_CANVAS) / (DARK_TEXT - DARK_CANVAS)) * 1000) / 10}%,var(--canvas))`);
const alphaName = (a) => `--w${Math.round(a * 1000)}`;
const alphaValue = (permille) => `color-mix(in srgb,var(--text) ${permille / 10}%,transparent)`;

const HEX = /#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![0-9a-fA-F])/g;
const WHITE_A = /rgba\(\s*255\s*,\s*255\s*,\s*255\s*,\s*(0?\.\d+|[01](?:\.0+)?)\s*\)/g;
const USED = /var\(--(n\d{1,3}|w\d{1,4})\)/g;

// rewrite one stretch of CSS; `used` collects the scale names it needs
export function convertCss(css, used) {
  // protect url(...) and the base-token :root blocks, which must keep literal values
  const keep = []; const hold = (m) => { keep.push(m); return `\u0000${keep.length - 1}\u0000`; };
  let t = css.replace(/url\((?:[^)(]|\([^)]*\))*\)/g, hold);
  t = t.replace(HEX, (m, h) => { const v = greyVar(h); if (!v) return m; used.add(v.slice(2)); return `var(${v})`; });
  t = t.replace(WHITE_A, (m, a) => { const n = alphaName(Number(a)); used.add(n.slice(2)); return `var(${n})`; });
  for (const m of t.matchAll(USED)) used.add(m[1]);
  return t.replace(/\u0000(\d+)\u0000/g, (_, i) => keep[+i]);
}
// in a stylesheet, everything is converted except the first :root{...} block when it defines --canvas (the base tokens)
function convertSheet(css, used) {
  const m = css.match(/:root\{[^}]*--canvas:[^}]*\}/);
  if (!m) return convertCss(css, used);
  return convertCss(css.slice(0, m.index), used) + m[0] + convertCss(css.slice(m.index + m[0].length), used);
}
const scaleBlock = (used) => {
  const n = [...used].filter((k) => k[0] === 'n').map((k) => +k.slice(1)).sort((a, b) => a - b), w = [...used].filter((k) => k[0] === 'w').map((k) => +k.slice(1)).sort((a, b) => a - b);
  return `${START}\n:root{${n.map((L) => `--n${L}:${greyValue(L)}`).join(';')};\n${w.map((p) => `--w${p}:${alphaValue(p)}`).join(';')}}\n${END}`;
};

export function run({ check = false } = {}) {
  const used = new Set(), out = new Map(), left = [];
  const sheets = fs.readdirSync(dir).filter((f) => f.endsWith('.css')).sort();
  for (const f of sheets) { const raw = fs.readFileSync(path.join(dir, f), 'utf8'); out.set(f, { raw, next: convertSheet(raw.replace(/\r\n/g, '\n'), used) }); }
  // index.html: only what is inside <style>…</style>, minus an existing scale block
  { const f = 'index.html', raw = fs.readFileSync(path.join(dir, f), 'utf8'); let html = raw.replace(/\r\n/g, '\n');
    const s = html.indexOf(START), e = html.indexOf(END); if (s >= 0 && e > s) html = html.slice(0, s) + html.slice(e + END.length).replace(/^\n/, '');
    html = html.replace(/(<style[^>]*>)([\s\S]*?)(<\/style>)/g, (_, a, css, z) => a + convertSheet(css, used) + z);
    out.set(f, { raw, next: html, html: true }); }
  // the scale goes straight after the base tokens in index.html
  { const o = out.get('index.html'); const m = o.next.match(/:root\{[^}]*--canvas:[^}]*\}/); if (!m) throw new Error('index.html: the base :root block was not found');
    const at = m.index + m[0].length; o.next = o.next.slice(0, at) + '\n' + scaleBlock(used) + o.next.slice(at); }
  for (const [f, o] of out) {
    const before = o.raw.replace(/\r\n/g, '\n');
    if (check) { if (before !== o.next) left.push(f); continue; }
    if (before === o.next) continue;
    if (o.next.length < before.length * 0.9) throw new Error(f + ' would shrink by more than a tenth; refusing');
    const text = o.raw.includes('\r\n') ? o.next.replace(/\n/g, '\r\n') : o.next;
    fs.writeFileSync(path.join(dir, f + '.tmp'), text, 'utf8'); fs.renameSync(path.join(dir, f + '.tmp'), path.join(dir, f));
    console.log('rewrote', f);
  }
  return { left, greys: [...used].filter((k) => k[0] === 'n').length, alphas: [...used].filter((k) => k[0] === 'w').length };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const check = process.argv.includes('--check'), r = run({ check });
  if (check && r.left.length) { console.error('hard-coded greys remain in: ' + r.left.join(', ') + '\nRun: node scripts/workspace-theme-colors.mjs'); process.exit(1); }
  console.log(check ? `every stylesheet is on the theme (${r.greys} greys, ${r.alphas} alphas)` : `scale: ${r.greys} greys, ${r.alphas} alphas`);
}
