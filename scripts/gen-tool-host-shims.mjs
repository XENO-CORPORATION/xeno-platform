// The tool page's shared modules (Hub's hostModules.ts, on the web). A tool package externalises `react`,
// `react/jsx-runtime` and `@xeno-tools/kit` so there is ONE React; tool-host.html's import map points those
// specifiers at these files, and each re-exports the instance the page already loaded (globalThis.__xenoHostModules).
// ESM named exports must be static, so the lists are written from the live modules here, and
// scripts/tool-packages.test.mjs fails when they drift (a React upgrade). Run: node scripts/gen-tool-host-shims.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(root, 'public', 'tool-host', 'modules');
const reactVersion = require('react/package.json').version;

// the kit's runtime is defineTool (xeno-tools packages/tool-kit/src/types.ts); everything else it exports is types
export const SPECIFIERS = {
  react: { file: `react@${reactVersion}.js`, names: Object.keys(require('react')) },
  'react/jsx-runtime': { file: `react-jsx-runtime@${reactVersion}.js`, names: Object.keys(require('react/jsx-runtime')) },
  '@xeno-tools/kit': { file: 'xeno-tools-kit@1.js', names: ['defineTool'] },
};

export function shimSource(specifier, names) {
  const lines = [
    `// generated by scripts/gen-tool-host-shims.mjs — do not edit`,
    `const m = globalThis.__xenoHostModules?.[${JSON.stringify(specifier)}];`,
    `if (!m) throw new Error(${JSON.stringify(`[xeno-tool] host module "${specifier}" is not registered`)});`,
    'export default (m.default !== undefined ? m.default : m);',
  ];
  for (const n of names) if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(n) && n !== 'default') lines.push(`export const ${n} = m[${JSON.stringify(n)}];`);
  return lines.join('\n') + '\n';
}

export const importMap = () => ({ imports: Object.fromEntries(Object.entries(SPECIFIERS).map(([s, v]) => [s, `/tool-host/modules/${v.file}`])) });

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  for (const [s, v] of Object.entries(SPECIFIERS)) fs.writeFileSync(path.join(OUT, v.file), shimSource(s, v.names));
  console.log(JSON.stringify(importMap(), null, 2));
}
